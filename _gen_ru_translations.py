def js_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def format_ru_block(data: dict) -> str:
    lines = ['  "ru": {']
    for key, val in data.items():
        lines.append(f'    "{key}": {js_string(val)},')
    lines[-1] = lines[-1].rstrip(",")
    lines.append("  }")
    return "\n".join(lines)


